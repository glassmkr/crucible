#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from the installed production tree
// (launch gate 11: notices are generator-owned and drift-checked in CI).
//
//   node scripts/gen-third-party-notices.mjs
//
// The tree is tiny (three packages, zero transitives), so the full license
// texts are embedded rather than referenced.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const out = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json"], { encoding: "utf8" }));
const pkgs = Object.keys(out.dependencies || {}).sort();

const lines = [
  "# Third-party notices",
  "",
  "The @glassmkr/crucible production dependency tree; full license texts",
  "follow. Generated by scripts/gen-third-party-notices.mjs from",
  "`npm ls --omit=dev --all`; do not edit by hand (CI drift-checks it).",
  "",
];

for (const p of pkgs) {
  const dir = path.join(process.cwd(), "node_modules", p);
  const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  lines.push(`## ${p}@${pj.version} (${pj.license})`, "");
  let lic = "";
  for (const f of ["LICENSE", "LICENSE.md", "LICENSE.txt", "License.md", "LICENCE"]) {
    const fp = path.join(dir, f);
    if (fs.existsSync(fp)) { lic = fs.readFileSync(fp, "utf8"); break; }
  }
  lines.push("```", lic.trim() || "(license text: see the package distribution)", "```", "");
}

fs.writeFileSync("THIRD_PARTY_NOTICES.md", lines.join("\n"));
console.log(`[notices] wrote THIRD_PARTY_NOTICES.md: ${pkgs.length} packages`);
